def run():
    print("Tier 6 - conformance vectors (frozen, primary-source derived)")
    for name, src, hexstr, proto, exp in VECTORS:
        raw = bytes.fromhex(hexstr)
        pdu = (decode_mrp if proto in ("MVRP", "MMRP") else decode_garp)(raw, proto)

        ok, why = True, []

        if "vlans" in exp:
            got = [a.as_vlan() for a in pdu.attributes if a.as_vlan() is not None]
            if got != exp["vlans"]:
                ok, _ = False, why.append(f"vlans {got} != {exp['vlans']}")
        if "macs" in exp:
            got = [a.as_mac() for a in pdu.attributes if a.as_mac() is not None]
            if got != exp["macs"]:
                ok, _ = False, why.append(f"macs {got} != {exp['macs']}")
        if "events" in exp:
            got = [a.event for a in pdu.attributes]
            if got != exp["events"]:
                ok, _ = False, why.append(f"events {got} != {exp['events']}")
        if "leaveall" in exp and pdu.leaveall_count != exp["leaveall"]:
            ok, _ = False, why.append(
                f"leaveall {pdu.leaveall_count} != {exp['leaveall']}")
        if "structural" in exp:
            got = [c for c, _ in pdu.structural]
            if got != exp["structural"]:
                ok, _ = False, why.append(f"structural {got} != {exp['structural']}")

        check(f"{src} {name}", ok, "; ".join(why))

    print(f"\n  {len(PASS)} passed, {len(FAIL)} failed")
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(run())
