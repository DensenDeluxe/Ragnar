#!/usr/bin/env python3
"""
mrpwatch conformance harness (Tier 6).

A frozen table of wire vectors with their expected decode. Every vector is a
literal hex string, hand-derived from a primary source and annotated with it.
Nothing here is generated by mrpwatch's own encoders - if the decoder drifts,
these vectors stop matching, which is the entire point.

This is the regression floor for the MVRP/MMRP half, which has no third-party
implementation to cross-check against (scapy has no MRP layer). Treat a failure
here as a decode defect, never as a vector to be "updated to match".

Sources:
  [K]  Linux net/802/mrp.c + include/net/mrp.h   (MVRP structures, packing)
  [A]  OpenAvnu daemons/mrpd/{mvrp,mmrp}.h       (attribute types, EtherTypes)
  [W]  Wireshark epan/etypes.h                   (EtherType registry)
  [S]  scapy.contrib.gxrp                        (GARP grammar)
"""

